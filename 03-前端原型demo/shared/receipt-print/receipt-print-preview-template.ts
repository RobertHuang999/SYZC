export function sliceReceiptPreviewRows<T>(
  rows: T[],
  paperSize: ReceiptPreviewPaperSize
): { first: T[]; rest: T[] } {
  const take = RECEIPT_PREVIEW_FIRST_PAGE_ROWS[paperSize]
  return { first: rows.slice(0, take), rest: rows.slice(take) }
}

