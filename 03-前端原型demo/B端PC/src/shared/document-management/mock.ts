// 内存单例存储（支持增改查）
let documentsState: DocumentItem[] = [...initialDocumentsMock]

export function getDocumentsByOrderNo(
  orderNo: string,
  orderType?: DocumentItem["orderType"]
): DocumentItem[] {
  const filtered = documentsState.filter((d) => d.orderNo === orderNo)
  if (filtered.length > 0) return filtered
  // 兜底：优先按调用方声明的单据类型返回模板
  if (orderType) {
    return documentsState.filter((d) => d.orderType === orderType)
  }
  // 未声明类型时按单号前缀推断（出库 CK 开头，其余按入库）
  return documentsState.filter((d) =>
    orderNo.startsWith("CK") ? d.orderType === "outbound" : d.orderType === "inbound"
  )
}

export function getAllDocuments(): DocumentItem[] {
  return documentsState
}

export function addDocumentItem(doc: Omit<DocumentItem, "id" | "createTime" | "hash">): DocumentItem {
  const newDoc: DocumentItem = {
    ...doc,
    id: `doc-${Date.now()}-${Math.floor(Math.random() * 1000)}`,
    createTime: new Date().toISOString().replace("T", " ").substring(0, 19),
    hash: Math.random().toString(16).substring(2) + Math.random().toString(16).substring(2),
  }
  // 插入并更新
  documentsState = [newDoc, ...documentsState]
  return newDoc
}

export function addDocumentItems(
  docs: Omit<DocumentItem, "id" | "createTime" | "hash">[]
): DocumentItem[] {
  const now = new Date().toISOString().replace("T", " ").substring(0, 19)
  const newDocs = docs.map((doc, idx) => ({
    ...doc,
    id: `doc-${Date.now()}-${idx}-${Math.floor(Math.random() * 1000)}`,
    createTime: now,
    hash: Math.random().toString(16).substring(2) + Math.random().toString(16).substring(2),
  }))
  documentsState = [...newDocs, ...documentsState]
  return newDocs
}

