export function resolvePrototypeRoute(record: {
  level1Menu: string
  level2Menu: string
  tab: string
}): string | null {
  const candidates = [record.tab, record.level2Menu, record.level1Menu].filter(Boolean)
  for (const label of candidates) {
    const route = prototypeRouteByMenuLabel[label]
    if (route) return route
  }
  return null
}
