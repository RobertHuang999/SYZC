function parseCreatorDisplay(display: string): { name: string; org: string } {
  const m = display.match(/^(.+?)\((.+)\)$/)
  if (m) return { name: m[1], org: m[2] }
  return { name: display, org: CURRENT_USER_ORG }
}

function approvedSeedToInboundRecord(seed: InboundApprovedSeed): InboundRecord {
  const { name, org } = parseCreatorDisplay(seed.creatorDisplay)
  return {
    id: seed.pcId,
    orderNo: seed.orderNo,
    ownerName: seed.ownerName,
    ownerType: seed.ownerType,
    ownerIdentifierMasked: seed.ownerIdentifierMasked,
    inboundType: seed.inboundType as InboundTypeLabel,
    inboundDate: seed.inboundDate,
    warehouseName: seed.warehouseName,
    houseName: seed.houseName,
    relatedOrderNo: seed.relatedOrderNo ?? null,
    goodsNames: [...seed.goodsNames],
    goodsLineItems: seed.goodsLineItems?.map((item) => ({ ...item })),
    inboundQuantity: seed.inboundQuantity,
    unit: seed.unit,
    creatorDisplay: seed.creatorDisplay,
    createByName: name,
    createOrgName: org,
    createdAt: seed.createdAt,
    checkStatus: 2,
  }
}

